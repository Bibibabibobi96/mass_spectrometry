function receipt=read_rf_saved_stationary_solution(request)
%READ_RF_SAVED_STATIONARY_SOLUTION Export frozen points without solving/saving.
required={'model_path','points_path','output_path'};
assert(isstruct(request)&&all(isfield(request,required)), ...
 'rf:StationaryExtraction','Saved stationary extraction request is incomplete.');
for name={'model_path','points_path'}
 assert(isfile(request.(name{1})),'rf:StationaryExtraction', ...
  'Required saved stationary input is missing: %s',name{1});
end
assert(~strcmpi(request.model_path,request.output_path), ...
 'rf:StationaryExtraction','Stationary output cannot overwrite the parent model.');
import com.comsol.model.util.*
tag=char(java.util.UUID.randomUUID());tag=['RF_STATIONARY_COLD_' strrep(tag,'-','_')];
model=mphload(request.model_path,tag);
cleanup=onCleanup(@()ModelUtil.remove(tag));
solutions=cell(model.sol.tags());
if any(strcmp(solutions,'sol_es'))
 cases=struct('case_id',{'differential','static'}, ...
  'solution_tag',{'sol_es','sol_es'}, ...
  'potential_expression',{'Vdiff','Vstatic'}, ...
  'Ex_expression',{'es.Ex','es_static.Ex'}, ...
  'Ey_expression',{'es.Ey','es_static.Ey'}, ...
  'Ez_expression',{'es.Ez','es_static.Ez'});
elseif all(ismember({'sol_es_diff','sol_es_static'},solutions))
 cases=struct('case_id',{'differential','static'}, ...
  'solution_tag',{'sol_es_diff','sol_es_static'}, ...
  'potential_expression',{'Vdiff','Vdiff'}, ...
  'Ex_expression',{'es.Ex','es.Ex'}, ...
  'Ey_expression',{'es.Ey','es.Ey'}, ...
  'Ez_expression',{'es.Ez','es.Ez'});
else
 error('rf:StationaryExtraction','Saved stationary solutions are missing.');
end
samples=export_comsol_stationary_field_samples(model, ...
 request.points_path,request.output_path,cases);
assert(height(samples)==2*height(readtable(request.points_path)), ...
 'rf:StationaryExtraction','Saved stationary sample coverage differs.');
receipt=struct('status','success','stationary_field_row_count',height(samples), ...
 'native_solves',0,'parent_model_saved',false);
clear cleanup
end
