function result = build_wehnelt_model(resolvedContractPath, runDirectory)
%BUILD_WEHNELT_MODEL Build the original three-stage unsolved MPH chain.
if nargin < 1 || isempty(resolvedContractPath)
    error('Wehnelt:MissingContract', ...
        'A resolved Wehnelt contract path is required; no defaults exist.');
end
if nargin < 2 || isempty(runDirectory)
    error('Wehnelt:MissingRunDirectory', ...
        'An explicit owner-provided Wehnelt run directory is required.');
end
contract = load_wehnelt_contract(char(resolvedContractPath));
assert(strcmp(contract.numerical.execution_mode, 'build_only'), ...
    'Wehnelt:NotBuildOnly', 'This entry builds only an unsolved Wehnelt model.');
geometry = phase1_geometry_coil_transverse(resolvedContractPath, runDirectory);
electrostatic = phase2_electrostatics_coil_transverse(resolvedContractPath, runDirectory);
thermal = phase4_thermal_emission_coil_transverse(resolvedContractPath, runDirectory);
assert(strcmp(geometry.status, 'PASS') && strcmp(electrostatic.status, 'PASS') ...
    && strcmp(thermal.status, 'PASS'), 'Wehnelt:StageFailed', ...
    'All three Wehnelt build stages must pass.');
assert(strcmp(electrostatic.execution_mode, 'build_only') ...
    && strcmp(thermal.execution_mode, 'build_only') ...
    && ~electrostatic.electrostatics_solved && ~thermal.electrostatics_solved ...
    && ~thermal.particle_tracing_solved, 'Wehnelt:UnexpectedSolve', ...
    'The build-only stages must not solve electrostatics or particle tracing.');
result = struct('status', thermal.status, ...
    'execution_mode', thermal.execution_mode, 'model_path', thermal.model_path, ...
    'contract_path', char(resolvedContractPath), ...
    'contract_project_id', contract.project_id, 'contract_model_id', contract.model_id, ...
    'selected_mode_id', contract.selected_mode_id, ...
    'parameter_bindings_verified', geometry.parameter_bindings_verified ...
        && electrostatic.parameter_bindings_verified && thermal.parameter_bindings_verified, ...
    'geometry_built', electrostatic.geometry_built, ...
    'mesh_built', electrostatic.mesh_built, ...
    'electrostatics_solved', electrostatic.electrostatics_solved ...
        || thermal.electrostatics_solved, ...
    'particle_tracing_solved', thermal.particle_tracing_solved, ...
    'candidate_evidence_allowed', thermal.candidate_evidence_allowed, ...
    'phases', struct('geometry', geometry, 'electrostatic', electrostatic, 'thermal', thermal));
end
