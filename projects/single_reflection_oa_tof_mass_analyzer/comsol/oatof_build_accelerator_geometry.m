function accelringtags = oatof_build_accelerator_geometry(geom1, acceleratorRingCount, interfacePort, geometry)
% REPOSITORY_CONTRACT: MATLAB_BUILD_ONLY
%OATOF_BUILD_ACCELERATOR_GEOMETRY Map instrument expressions to the component API.
% The independent project owns solid construction. Existing COMSOL feature tags
% and instrument parameters are retained for downstream selections and CAD.
if nargin < 3, interfacePort = struct('enabled',false); end
if nargin < 4, geometry = struct(); end
layout = struct( ...
    'ring_count', acceleratorRingCount, ...
    'x_center', 'x_accel_center', 'y_center', '0', ...
    'repeller_front_z', 'z_accel_origin', ...
    'electrode_half_width', 'accel_shield_half-accel_ring_gap', ...
    'repeller_thickness', 'accel_repeller_thickness', ...
    'shield_inner_half_width', 'accel_shield_half', ...
    'shield_wall', 'accel_shield_wall', ...
    'total_length', 'L_accel', 'rear_gap', 'accel_shield_back_extra', ...
    'ring_bore_half_width', 'accel_ring_bore_half', ...
    'ring_thickness', 'accel_ring_thickness', ...
    'boolean_cut_padding_mm', 0.1);
layout.ring_z = arrayfun(@(k) sprintf('(%s)+%d*(%s)/%d', ...
    'z_accel_grid1',k,'accel_stage2_length',acceleratorRingCount+1), ...
    1:acceleratorRingCount,'UniformOutput',false);
if ~isempty(fieldnames(geometry))
    g=geometry;
    assert(strcmp(g.cross_section,'square'),'oatof:AcceleratorCrossSection', ...
        'COMSOL accelerator supports the explicit square section only.');
    layout.x_center=mm(g.axis_x_mm); layout.y_center=mm(g.axis_y_mm);
    layout.repeller_front_z=mm(g.repeller_front_z_mm);
    layout.electrode_half_width=mm(g.electrode_width_mm/2);
    layout.repeller_thickness=mm(g.repeller_thickness_mm);
    layout.shield_inner_half_width=mm(g.shield_inner_width_mm/2);
    layout.shield_wall=mm(g.shield_wall_mm);
    layout.total_length=mm(g.grid2_z_mm-g.repeller_front_z_mm);
    layout.rear_gap=mm(g.repeller_front_z_mm-g.repeller_thickness_mm-g.shield_back_z_mm-g.shield_wall_mm);
    layout.ring_bore_half_width=mm(g.bore_width_mm/2);
    layout.ring_thickness=mm(g.ring_thickness_mm);
    layout.ring_z=arrayfun(@mm,g.ring_z_mm(:).','UniformOutput',false);
    layout=rmfield(layout,'boolean_cut_padding_mm');
    if isempty(fieldnames(interfacePort))
        interfacePort=struct('enabled',false);
    else
        opening=interfacePort;
        assert(isequal(sort(fieldnames(opening)),sort({'center_mm';'width_mm';'height_mm'})), ...
            'oatof:SideOpening','Explicit mechanical side opening fields are required.');
        center=opening.center_mm;
        assert(isnumeric(center) && numel(center)==3 && all(isfinite(center)) && ...
            abs(center(1)-g.negative_x_face_mm)<=1e-9, ...
            'oatof:SideOpening','Mechanical opening must lie on the provider outer negative-x face.');
        assert(isfinite(opening.width_mm) && opening.width_mm>0 && ...
            isfinite(opening.height_mm) && opening.height_mm>0 && ...
            abs(center(2)-g.axis_y_mm)+opening.width_mm/2<g.shield_inner_width_mm/2 && ...
            center(3)-opening.height_mm/2>g.repeller_front_z_mm && ...
            center(3)+opening.height_mm/2<g.grid1_z_mm, ...
            'oatof:SideOpening','Mechanical opening must fit inside the actual first gap.');
        interfacePort=struct('enabled',true,'full_width_y_mm',opening.width_mm, ...
            'full_height_z_mm',opening.height_mm,'center_y_mm',center(2),'center_z_mm',center(3));
    end
end
projectsRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
componentDir = fullfile(projectsRoot, 'orthogonal_accelerator', 'comsol');
previousPath = path;
restorePath = onCleanup(@() path(previousPath)); %#ok<NASGU>
addpath(componentDir);
accelringtags = build_sectioned_geometry(geom1, layout, interfacePort);
end

function value=mm(number)
value=sprintf('%.17g[mm]',number);
end
