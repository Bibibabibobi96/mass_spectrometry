function validation=oatof_validate_candidate_solution(model,result,contract)
%OATOF_VALIDATE_CANDIDATE_SOLUTION Read-only complete Candidate model checks.
% Shared by the ordinary build and an explicitly admitted saved-model replay.
arguments
    model
    result (1,1) struct
    contract (1,1) struct
end
assert(result.nP == 100 && result.nDet == 100, ...
    'Candidate detected only %d/%d particles.', result.nDet, result.nP);
assert(numel(result.detectorStatus) == result.nP && ...
    all(result.detectorStatus == "detector_hit"), ...
    'Detector extraction did not classify each particle exactly once.');
stage1Rings = round(model.param.evaluate('N_rings1'));
stage2Rings = round(model.param.evaluate('N_rings2'));
assert(stage1Rings == contract.rings.stage1_count && ...
    stage2Rings == contract.rings.stage2_count, ...
    'Parameterized ring counts differ from the candidate contract.');
timeList = string(model.study('std2').feature('time1').getString('tlist'));
requiredTimeTokens = ["cpt_dt_fine", "cpt_dt_drift", ...
    "cpt_t_refl_start", "cpt_t_refl_end", ...
    "cpt_t_detector_start", "cpt_t_detector_end"];
assert(all(arrayfun(@(token) contains(timeList, token), requiredTimeTokens)), ...
    'Segmented particle time window is incomplete: %s', timeList);
assert(strcmp(model.result.dataset('pdset1').getString('solution'), 'sol2'), ...
    'Particle dataset is not linked uniquely to sol2.');
validation=struct('stage1_rings',stage1Rings,'stage2_rings',stage2Rings, ...
    'time_window_token_count',numel(requiredTimeTokens));
end
