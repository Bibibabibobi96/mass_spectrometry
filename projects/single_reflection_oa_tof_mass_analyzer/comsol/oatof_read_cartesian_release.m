function [release,data] = oatof_read_cartesian_release(path,massAmu,particleCount)
%OATOF_READ_CARTESIAN_RELEASE Read the frozen global Cartesian source in order.
arguments
    path (1,1) string
    massAmu (1,1) double {mustBePositive,mustBeFinite}
    particleCount (1,1) double = NaN
end
release=readtable(path,'VariableNamingRule','preserve');
columns={'particle_id','mass_amu','charge_state','x_mm','y_mm','z_mm', ...
    'vx_m_per_s','vy_m_per_s','vz_m_per_s','kinetic_energy_eV'};
assert(isequal(release.Properties.VariableNames,columns), ...
    'oatof:CartesianColumns','Cartesian release columns or ordering differ from the contract.');
assert(all(varfun(@isnumeric,release,'OutputFormat','uniform')) && ...
    all(isfinite(release{:,:}),'all') && height(release)>0, ...
    'oatof:CartesianValues','Cartesian release values must be finite numeric values.');
ids=release.particle_id;
assert(all(ids>0 & ids==floor(ids)) && numel(unique(ids))==height(release), ...
    'oatof:CartesianIdentity','Cartesian release particle identity is invalid.');
assert(all(abs(release.mass_amu-massAmu)<1e-9) && all(release.charge_state==1), ...
    'oatof:CartesianSpecies','Cartesian release species differs.');
assert(isnan(particleCount) || (isfinite(particleCount) && particleCount>0 && ...
    particleCount==floor(particleCount) && height(release)==particleCount), ...
    'oatof:CartesianCount','Cartesian release count differs.');
assert(all(release.kinetic_energy_eV>=0), ...
    'oatof:CartesianValues','Cartesian release energy must be nonnegative.');
% Geometry is in mm; velocity is already SI, with no angular reconstruction.
data=release{:,{'x_mm','y_mm','z_mm','vx_m_per_s','vy_m_per_s','vz_m_per_s'}};
end
