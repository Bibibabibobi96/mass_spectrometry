function contract = load_oatof_contract(contractPath)
%LOAD_OATOF_CONTRACT Load the generated oa-TOF resolved machine contract.
% Humans edit baseline.json and modes/formal.json; programs consume only
% resolved_geometry.json so every language sees the same derived values.

projectRoot = fileparts(mfilename('fullpath'));
if nargin < 1 || strlength(string(contractPath)) == 0
    contractPath = fullfile(projectRoot, 'config', 'resolved_geometry.json');
end
contractPath = char(contractPath);
assert(isfile(contractPath), 'oatof:MissingResolvedContract', ...
    ['Missing resolved contract "%s". Generate the formal contract with ' ...
     'analysis/resolve_geometry.py --write or compile an isolated candidate.'], ...
    contractPath);
contract = jsondecode(fileread(contractPath));
assert(contract.schema_version == 1 && ...
    strcmp(contract.role, 'oa_tof_resolved_contract_do_not_edit'), ...
    'oatof:ResolvedSchema', 'Unsupported resolved contract schema.');
assert(isfield(contract,'comsol_runtime') && ...
    all(isfield(contract.comsol_runtime,{'solver_steps','times_to_store'})), ...
    'oatof:SolverPolicy','Resolved contract lacks its COMSOL time-step policy.');
runtime = contract.comsol_runtime;
assert(isscalar(string(runtime.solver_steps)) && ...
    any(string(runtime.solver_steps) == ["free","intermediate","strict"]) && ...
    isscalar(string(runtime.times_to_store)) && ...
    string(runtime.times_to_store) == "tlist", ...
    'oatof:SolverPolicy','Resolved contract contains an unsupported COMSOL time-step policy.');

g = contract.geometry_mm;
a = contract.geometry_derivation.accelerator;
s = contract.particle_source;
must_be_near(g.accelerator_grid1_z, g.accelerator_repeller_z + a.d1_mm, ...
    'accelerator grid1 z');
must_be_near(g.accelerator_grid2_z, g.accelerator_grid1_z + a.d2_mm, ...
    'accelerator grid2 z');
must_be_near(g.accelerator_focus_z, ...
    g.accelerator_grid2_z + a.focus_drift_after_grid2_mm, ...
    'accelerator focus z');
assert(isnumeric(g.detector_z) && isscalar(g.detector_z) && isfinite(g.detector_z) && ...
    isnumeric(contract.coordinate_convention.detector_x) && ...
    isscalar(contract.coordinate_convention.detector_x) && ...
    isfinite(contract.coordinate_convention.detector_x), ...
    'oatof:DetectorPosition','Resolved detector x/z must be finite scalar coordinates.');
must_be_near(g.L_accel, a.d1_mm + a.d2_mm, 'accelerator total length');
must_be_near(g.L_reflectron, g.L_stage1 + g.L_stage2, ...
    'reflectron total length');
if isfield(contract,'accelerator_topology')
    topology=contract.accelerator_topology;
    planes=topology.planes_global_z_mm;
    assert(strcmp(topology.topology_id,'three_zone_accelerator_ideal_v1') && ...
        all(isfield(planes,{'repeller','intermediate1','intermediate2','exit'})), ...
        'oatof:ResolvedDerivation','Unsupported accelerator topology.');
    values=[planes.repeller,planes.intermediate1,planes.intermediate2,planes.exit];
    assert(all(isfinite(values)) && all(diff(values)>0), ...
        'oatof:ResolvedDerivation','Three-zone planes must be finite and ordered.');
    must_be_near(g.accelerator_repeller_z,planes.repeller,'three-zone repeller');
    must_be_near(g.accelerator_grid1_z,planes.intermediate1,'three-zone grid1');
    must_be_near(g.accelerator_grid2_z,planes.exit,'three-zone exit');
    must_be_near(a.zone2_length_mm,planes.intermediate2-planes.intermediate1,'zone2 length');
    must_be_near(a.zone3_length_mm,planes.exit-planes.intermediate2,'zone3 length');
    must_be_near(a.d2_mm,a.zone2_length_mm+a.zone3_length_mm,'downstream total length');
    for pair={{'repeller','repeller'},{'grid1','intermediate1'},{'intermediate2','intermediate2'},{'grid2','exit'}}
        item=pair{1};
        must_be_near(contract.electrodes_V.(item{1}),topology.potentials_v.(item{2}),['topology voltage ' item{1}]);
    end
end
must_be_near(s.center_x_mm, ...
    contract.coordinate_convention.accelerator_axis_x, 'source x/axis');
if strcmp(s.center_z_rule, ...
        'accelerator_repeller_z + accelerator_stage1_length_mm/2')
    expectedSourceZ = g.accelerator_repeller_z + a.d1_mm/2;
    if abs(double(s.center_z_mm)-double(expectedSourceZ)) > 1e-10 && ...
            isfield(a, 'finite_interval_theory')
        theory = a.finite_interval_theory;
        finiteIntervalSourceZ = theory.canonical_repeller_z_mm + ...
            theory.source_center_mm;
        if abs(double(s.center_z_mm)-double(finiteIntervalSourceZ)) <= 1e-10
            expectedSourceZ = finiteIntervalSourceZ;
        end
    end
elseif strcmp(s.center_z_rule, ...
        ['accelerator_topology.planes_global_z_mm.repeller + ' ...
         'geometry_derivation.accelerator.source_center_from_repeller_mm'])
    assert(isfield(contract,'accelerator_topology'),'oatof:SourceCenterRule','Three-zone source requires topology.');
    expectedSourceZ=contract.accelerator_topology.planes_global_z_mm.repeller+a.source_center_from_repeller_mm;
elseif strcmp(s.center_z_rule, ...
        ['geometry_derivation.accelerator.finite_interval_theory.' ...
         'canonical_repeller_z_mm + source_center_mm'])
    theory = a.finite_interval_theory;
    expectedSourceZ = theory.canonical_repeller_z_mm + theory.source_center_mm;
else
    error('oatof:SourceCenterRule', ...
        'Unsupported particle_source.center_z_rule: %s', s.center_z_rule);
end
must_be_near(s.center_z_mm, expectedSourceZ, 'source center z');
end

function must_be_near(actual, expected, label)
assert(abs(double(actual) - double(expected)) <= 1e-10, ...
    'oatof:ResolvedDerivation', ...
    '%s is inconsistent: actual=%.17g expected=%.17g', ...
    label, actual, expected);
end
