function validate_finite_source_start(source,metadata,releasePlaneZ)
% Consume the frozen canonical preflight boundary; do not invent a source mode.
assert(strcmp(metadata.role,'multipole_canonical_particle_source_metadata'), ...
    'multipole:sourceStart:metadata','Canonical source metadata is required.');
assert(height(source)==metadata.particle_count, ...
    'multipole:sourceStart:population','Source population differs from preflight.');
assert(all(source.mass_amu==metadata.mass_amu) && all(source.charge_state==metadata.charge_state), ...
    'multipole:sourceStart:species','Source species differs from preflight.');
values=source{:,{'x_mm','y_mm','z_mm','vx_m_s','vy_m_s','vz_m_s','birth_time_s'}};
assert(all(isfinite(values),'all') && all(source.birth_time_s>=0), ...
    'multipole:sourceStart:state','Source state or absolute clock is invalid.');
if isfield(metadata,'source_volume_snapshot') && isequal(metadata.source_volume_snapshot,true)
    assert(strcmp(metadata.energy_model_authority,'continuous_axial_volume_source_receipt') && ...
        isempty(metadata.source_plane_z_mm) && isempty(metadata.operating_point_binding), ...
        'multipole:sourceStart:volumeAuthority','Volume snapshot lacks canonical receipt authority.');
else
    assert(all(abs(source.z_mm-releasePlaneZ)<1e-12), ...
        'multipole:sourceStart:plane','Particle source differs from the canonical release plane.');
end
end
