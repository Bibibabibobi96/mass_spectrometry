function acceptance=validate_finite_extraction_context(source,metadata,context)
%VALIDATE_FINITE_EXTRACTION_CONTEXT Require explicit frozen task values.
required={'solution_on','solution_zero','dataset_on','dataset_zero','native_order', ...
 'source_ids','source_birth_s','geometry','acceptance','census_radius_mm','drive', ...
 'primary_case_id','control_case_id','outputs','resolved_design_sha256'};
assert(isstruct(context)&&all(isfield(context,required)), ...
 'rf:ExtractionContext','Frozen extraction context is incomplete.');
assert(strcmp(metadata.role,'multipole_canonical_particle_source_metadata'), ...
 'rf:ExtractionSource','Frozen source metadata role differs.');
assert(isfield(metadata,'parent_resolved_design_sha256')&& ...
 strcmp(context.resolved_design_sha256,metadata.parent_resolved_design_sha256), ...
 'rf:ExtractionSource','Extraction context is not bound to frozen source design.');
columns={'particle_id','birth_time_s','x_mm','y_mm','z_mm','vx_m_s','vy_m_s','vz_m_s','mass_amu','charge_state'};
assert(istable(source)&&all(ismember(columns,source.Properties.VariableNames)), ...
 'rf:ExtractionSource','Frozen canonical source columns are missing.');
assert(all(isfinite(source{:,columns}),'all')&&height(source)>0, ...
 'rf:ExtractionSource','Frozen source has nonfinite values.');
ids=source.particle_id(:);order=context.native_order(:);
assert(numel(unique(ids))==height(source)&&all(ids>0&ids<=flintmax&ids==fix(ids))&& ...
 isequal(sort(order),(1:height(source))'), ...
 'rf:ExtractionMapping','Native order must be an explicit complete permutation.');
assert(isequal(context.source_ids(:),ids)&& ...
 isequal(context.source_birth_s(:),source.birth_time_s(:)), ...
 'rf:ExtractionMapping','Mapping IDs or birth times differ from frozen source.');
assert(all(source.mass_amu==metadata.mass_amu)&&all(source.charge_state==metadata.charge_state), ...
 'rf:ExtractionSource','Frozen source species differs from metadata.');
assert(all(isfield(context.geometry,{'census_plane_z','rod_z_min','rod_z_max', ...
 'handoff_plane_z','entrance_port_plane_z','exit_port_plane_z'}))&& ...
 all(isfield(context.acceptance,{'working_region_radius','entrance_interface','exit_interface'}))&& ...
 all(isfield(context.drive,{'frequency_Hz','phase_rad'})), ...
 'rf:ExtractionContext','Frozen geometry, acceptance or clock is incomplete.');
outputs={'events','trajectories','canonical','primary_canonical','control_canonical', ...
 'primary_trajectories','control_trajectories'};
assert(all(isfield(context.outputs,outputs)), ...
 'rf:ExtractionContext','Explicit output destinations are incomplete.');
assert(~isempty(context.outputs.events)&&~isempty(context.outputs.trajectories), ...
 'rf:ExtractionContext','Required output destinations are empty.');
assert(strcmp(context.solution_on,'sol_on')&&strcmp(context.solution_zero,'sol_zero')&& ...
 ~strcmp(context.dataset_on,context.dataset_zero), ...
 'rf:ExtractionContext','Frozen finite solution/dataset binding differs.');
acceptance=context.acceptance;
for name={'entrance_interface','exit_interface'}
 interface=acceptance.(name{1});
 assert(isfield(interface,'cross_section')&&~isfield(interface,'aperture_radius_mm'), ...
  'rf:ExtractionPort','Use the original explicit cross-section, not a serialized inferred radius.');
 interface.aperture_radius_mm=sectionRadius(interface.cross_section);
 acceptance.(name{1})=interface;
end
end

function radius=sectionRadius(section)
assert(isstruct(section)&&isscalar(section)&&isfield(section,'shape'), ...
 'rf:ExtractionPort','Frozen port cross-section is missing.');
if strcmp(section.shape,'circle')
 assert(isfield(section,'radius_mm')&&isnumeric(section.radius_mm)&& ...
  isscalar(section.radius_mm)&&isfinite(section.radius_mm)&&section.radius_mm>0, ...
  'rf:ExtractionPort','Finite circular port radius must be positive and finite.');
 radius=section.radius_mm;
elseif strcmp(section.shape,'open_rod_envelope')
 % Original open envelope is a reference, not a finite aperture.
 assert(isfield(section,'inscribed_radius_mm')&&isnumeric(section.inscribed_radius_mm)&& ...
  isscalar(section.inscribed_radius_mm)&&isfinite(section.inscribed_radius_mm)&&section.inscribed_radius_mm>0, ...
  'rf:ExtractionPort','Open port reference envelope is incomplete.');
 radius=Inf;
else
 error('rf:ExtractionPort','Unsupported frozen port cross-section.');
end
end
