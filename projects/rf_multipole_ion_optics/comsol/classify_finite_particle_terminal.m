function outcome = classify_finite_particle_terminal(record, accepted, rejectionReason)
%CLASSIFY_FINITE_PARTICLE_TERMINAL Keep observation and acceptance as separate facts.
% Finite samples at final inventory are not a claim of native alive status.
% No native loss cause is read by the current extractor, so absence is unknown.
arguments
    record (1,1) struct
    accepted (1,1) logical
    rejectionReason (1,:) char = ''
end
assert(isfield(record,'terminal_observation'), 'rf:TerminalObservation', ...
    'Current extractor terminal observation is required; legacy causes are not inferred.');
observation=record.terminal_observation;
required={'solution_end_index','solution_end_time_s','last_finite_solution_index', ...
    'last_finite_time_s','finite_at_solution_end','finite_track_ended','native_termination_cause'};
assert(isstruct(observation)&&all(isfield(observation,required)), ...
    'rf:TerminalObservation','Terminal observation fields are incomplete.');
assert(isfinite(observation.solution_end_index)&&observation.solution_end_index>=1&& ...
    observation.solution_end_index==fix(observation.solution_end_index)&& ...
    isfinite(observation.last_finite_solution_index)&&observation.last_finite_solution_index>=1&& ...
    observation.last_finite_solution_index==fix(observation.last_finite_solution_index)&& ...
    observation.last_finite_solution_index<=observation.solution_end_index&& ...
    isfinite(observation.solution_end_time_s)&&isfinite(observation.last_finite_time_s)&& ...
    observation.last_finite_time_s<=observation.solution_end_time_s, ...
    'rf:TerminalObservation','Terminal observation time/index facts are invalid.');
assert(islogical(observation.finite_at_solution_end)&&isscalar(observation.finite_at_solution_end)&& ...
    islogical(observation.finite_track_ended)&&isscalar(observation.finite_track_ended)&& ...
    observation.finite_at_solution_end==(observation.last_finite_solution_index==observation.solution_end_index)&& ...
    ~(observation.finite_at_solution_end&&observation.finite_track_ended)&& ...
    strcmp(observation.native_termination_cause,'not_observed'), ...
    'rf:TerminalObservation','Terminal observation facts contradict one another.');
rejected=~isempty(rejectionReason)&&~strcmp(rejectionReason,'none');
assert(~accepted||~rejected,'rf:TerminalAcceptance','Accepted state cannot have a rejection reason.');
outcome=struct('status','unknown','reason','terminal_cause_unresolved', ...
    'acceptance_status','unresolved','acceptance_reason','none');
if accepted
    outcome.status='transmitted';outcome.reason='acceptance_surface';
    outcome.acceptance_status='accepted';
else
    if rejected
        outcome.acceptance_status='rejected';outcome.acceptance_reason=rejectionReason;
    end
    if observation.finite_at_solution_end
        outcome.reason='time_window_end';
    elseif observation.finite_track_ended
        outcome.reason='ended_without_loss_evidence';
    end
end
end
