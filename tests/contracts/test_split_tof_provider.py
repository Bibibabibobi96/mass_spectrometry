import hashlib
import json
from pathlib import Path
import unittest
from msplatform import assembly, components, examples
from msplatform.components.single_reflection_tof.legacy_projection import project_legacy_downstream
from msplatform.components.single_reflection_oa_tof.accelerator_geometry import resolve_accelerator_geometry, apply_side_opening, resolve_oa_provider
from msplatform.components.single_reflection_oa_tof.geometry_members import iter_geometry_members
from msplatform.components.single_reflection_oa_tof.geometry_contract import resolve_electrode_geometry
from msplatform.components.single_reflection_tof.registration import members as downstream_members
from msplatform.components.orthogonal_accelerator.geometry_members import iter_geometry_members as oa_members
from msplatform.components.shape_query import shape_relation
from msplatform.contracts.machine_contracts import ContractError

class SplitTofProviderTests(unittest.TestCase):
    def test_physical_projection_matches_independent_legacy_fixture(self):
        # This oracle was generated by executing the geometry_contract.py at
        # source_commit, before the downstream formulas were extracted.
        fixture = json.loads((Path(__file__).parent / "fixtures" / "split_tof_legacy_projection.json").read_text(encoding="utf-8"))
        request = examples.load_example(fixture["example_id"]).component_requests["oatof"]
        resolved = components.resolve_component(request).resolved_design
        def digest(value):
            encoded = json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False).encode("utf-8")
            return hashlib.sha256(encoded).hexdigest()
        self.assertEqual(digest(request), fixture["author_request_sha256"])
        self.assertEqual(digest(resolved), fixture["resolved_contract_sha256"])
        physical = resolve_electrode_geometry(resolved)
        self.assertEqual(len(physical["electrodes"]), 45)
        for key in ("electrodes", "detector_active_face", "local_extents"):
            with self.subTest(projection=key):
                self.assertEqual(physical[key], fixture[key])

    def test_real_frozen_projection_preserves_members(self):
        study = examples.load_example("rf_oatof_functional_v1")
        old = components.resolve_component(study.component_requests["oatof"]).resolved_design
        projection = apply_side_opening(resolve_accelerator_geometry(old, variant_id="three_zone_square"), side_opening=old["mechanical_side_opening"])
        instrument_oa = resolve_oa_provider(old, projection=projection, geometry_profile_id=None)
        oa = components.resolve_component({"provider_id": "orthogonal_accelerator", "design": {"instrument_geometry": instrument_oa["source"]}})
        self.assertEqual(oa.resolved_design, instrument_oa["mechanical"])
        import copy
        for key, value in (("producer", "unknown"), ("frame_id", "unknown"), ("schema_version", 2)):
            invalid = copy.deepcopy(instrument_oa["source"])
            invalid[key] = value
            with self.subTest(invalid_source=key), self.assertRaises(ValueError):
                components.resolve_component({"provider_id": "orthogonal_accelerator", "design": {"instrument_geometry": invalid}})
        invalid = copy.deepcopy(instrument_oa["source"])
        invalid["geometry"]["port_center_z_mm"] = invalid["geometry"]["grid2_z_mm"]
        with self.assertRaises(ValueError):
            components.resolve_component({"provider_id": "orthogonal_accelerator", "design": {"instrument_geometry": invalid}})
        design = project_legacy_downstream(old)
        tof = components.resolve_component({"provider_id": "single_reflection_tof", "design": design})
        self.assertFalse(any("accelerator" in key for key in design))
        before = iter_geometry_members(old)
        expected_oa = {v["member_id"].removeprefix("accelerator/"): v for v in before if v["member_id"].startswith("accelerator/")}
        actual_oa = {v["member_id"]: v for v in oa_members(oa.resolved_design)}
        self.assertEqual(set(expected_oa), set(actual_oa))
        for name in actual_oa:
            self.assertEqual(expected_oa[name]["shape"], actual_oa[name]["shape"])
            self.assertEqual(expected_oa[name]["representation_role"], actual_oa[name]["representation_role"])
        expected = {v["member_id"]: v for v in before if not v["member_id"].startswith("accelerator/")}
        actual = {v["member_id"]: v for v in downstream_members(tof.resolved_design, tof.assembly_interface)}
        self.assertEqual(set(expected), set(actual))
        for name in actual:
            for key in ("shape", "representation_role", "electrode_group_id"):
                self.assertEqual(expected[name][key], actual[name][key])
        self.assertEqual(tof.assembly_interface["vacuum_domains"][0]["radius_mm"], 350.0)
        self.assertEqual(tof.assembly_interface["ports"], {})
        self.assertEqual(oa.assembly_interface["schema_version"], 4)
        def pose(frame):
            return {"schema_version": 1, "role": "rigid_transform", "from_frame_id": frame,
                    "to_frame_id": "oatof_global", "rotation": [[1, 0, 0], [0, 1, 0], [0, 0, 1]],
                    "translation_mm": [0, 0, 0]}
        recipe = {"schema_version": 2, "role": "assembly_recipe", "integration_id": "instrument_assembly",
                  "recipe_id": "oa_downstream", "assembly_frame_id": "oatof_global",
                  "position_tolerance_mm": 1e-8, "angular_tolerance_rad": 1e-10,
                  "instances": [{"instance_id": "oa", "project_id": "orthogonal_accelerator",
                                 "transform": pose(oa.assembly_interface["local_frame_id"])},
                                {"instance_id": "tof", "project_id": "single_reflection_tof",
                                 "transform": pose(tof.assembly_interface["local_frame_id"])}],
                  "connections": [], "containments": [{"relation_id": "oa_inside_tof",
                      "container_instance_id": "tof", "contained_instance_id": "oa",
                      "domain_id": "flight_tube_cavity", "coupling_mode": "monolithic_joint_solve"}]}
        instrument = assembly.assemble(recipe, {"oa": oa, "tof": tof})
        self.assertEqual(instrument.composition_plan["schema_version"], 6)
        self.assertEqual(instrument.composition_plan["scope"]["containment_ids"], ["oa_inside_tof"])
        # The original grounded detector overlaps the OA shield at this point.
        # Containment describes the enclosure, not absence of physical contact.
        point = [58.0, 0.0, -0.5]
        self.assertEqual(shape_relation(actual_oa["grounded_shield"]["shape"], point), "interior")
        self.assertEqual(shape_relation(actual["detector"]["shape"], point), "interior")
        self.assertEqual(expected_oa["grounded_shield"]["electrode_group_id"], "common_ground")
        self.assertEqual(expected["detector"]["electrode_group_id"], "common_ground")
        altered = tof.assembly_interface
        altered["material_bounds_mm"]["max"][0] += 1
        forged = components.ResolvedComponent(tof.provider_id, tof.resolved_design, altered, source_design=tof.source_design)
        with self.assertRaises(ContractError):
            assembly.assemble(recipe, {"oa": oa, "tof": forged})
        altered = oa.assembly_interface
        altered["material_bounds_mm"]["max"][0] -= 1
        forged_oa = components.ResolvedComponent(oa.provider_id, oa.resolved_design, altered, source_design=oa.source_design)
        with self.assertRaises(ContractError):
            assembly.assemble(recipe, {"oa": forged_oa, "tof": tof})

    def test_invalid_inputs_fail(self):
        import copy
        study = examples.load_example("rf_oatof_functional_v1")
        old = components.resolve_component(study.component_requests["oatof"]).resolved_design
        design = project_legacy_downstream(old)
        for update in ({"irrelevant_oa": 1}, {"schema_version": 2}):
            changed = copy.deepcopy(design); changed.update(update)
            with self.assertRaises((ValueError, ContractError)):
                components.resolve_component({"provider_id": "single_reflection_tof", "design": changed})
        design["electrodes_v"]["entgrid"] = 1
        with self.assertRaises(ValueError):
            components.resolve_component({"provider_id": "single_reflection_tof", "design": design})

if __name__ == "__main__": unittest.main()
